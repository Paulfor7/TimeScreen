import {_electron as electron} from '@playwright/test';
import assert from 'node:assert/strict';
import fs from 'node:fs';
import path from 'node:path';
const userData=path.resolve('.local/desktop-test-'+Date.now());
fs.mkdirSync(userData,{recursive:true});
const options={executablePath:path.resolve('release/win-unpacked/TimeScreen.exe'),env:{...process.env,TIMESCREEN_DATA_DIR:userData},args:[]};
let app=await electron.launch(options),page=await app.firstWindow();
await page.getByRole('button',{name:'创建第一个项目'}).click();
await page.locator('#project-name').fill('桌面验证');
await page.getByRole('button',{name:'创建项目',exact:false}).click();
await page.getByRole('button',{name:'正向计时',exact:true}).click();
await page.getByRole('button',{name:'开始专注',exact:true}).click();
await page.waitForFunction(()=>document.querySelector('#clock')?.textContent!=='00:00');
await page.evaluate(()=>window.close());
await new Promise(resolve=>app.process().once('exit',resolve));
const file=path.join(userData,'timescreen.json');
const first=JSON.parse(fs.readFileSync(file,'utf8'));
assert.equal(first.projects[0].name,'桌面验证');assert.ok(first.active.lastSeen>=first.active.startedAt);
app=await electron.launch(options);page=await app.firstWindow();
await page.getByRole('button',{name:'继续专注',exact:true}).waitFor();
await page.getByRole('button',{name:'继续专注',exact:true}).click();
await page.getByTitle('完成并保存').click();
await page.getByRole('button',{name:'结束休息'}).click();
await page.evaluate(()=>window.close());
await new Promise(resolve=>app.process().once('exit',resolve));
const result=JSON.parse(fs.readFileSync(file,'utf8'));
assert.equal(result.sessions.length,1);assert.equal(result.active,null);assert.ok(fs.existsSync(file+'.bak'));
console.log('Desktop passed: native IPC storage, exact save on close, relaunch recovery, resume, record persistence, backup file.');
