import {_electron as electron} from '@playwright/test';
import fs from 'node:fs';
import path from 'node:path';
import assert from 'node:assert/strict';
import {initialData} from '../src/model.js';
const root=path.resolve('.local/desktop-appearance-'+Date.now());fs.mkdirSync(root,{recursive:true});
const file=path.join(root,'timescreen.json'),seed=initialData();
seed.settings.background='data:image/png;base64,'+fs.readFileSync('assets/icon.png').toString('base64');seed.settings.overlay=85;
seed.projects=[{id:'test',name:'桌面图片测试',color:'#7b8cde',icon:'folder'}];
fs.writeFileSync(file,JSON.stringify(seed));
const packaged=process.env.TEST_PACKAGED==='1';
const options={executablePath:path.resolve(packaged?'release/win-unpacked/TimeScreen.exe':'node_modules/electron/dist/electron.exe'),args:packaged?[]:['.'],env:{...process.env,TIMESCREEN_DATA_DIR:root}};
let app=await electron.launch(options),page=await app.firstWindow();
await page.waitForFunction(()=>document.body.classList.contains('custom-bg'));
assert.equal(await page.evaluate(()=>document.body.style.getPropertyValue('--veil')),'0.45');
await page.getByTitle('编辑项目').click();
await page.locator('#project-logo-file').setInputFiles('assets/icon.png');
await page.waitForFunction(()=>document.querySelector('#logo-preview img')?.naturalWidth>0);
await page.getByRole('button',{name:'保存修改'}).click();
await page.getByRole('button',{name:'偏好设置',exact:true}).click();
await page.locator('#background-file').setInputFiles('assets/icon.png');
await page.getByRole('status').filter({hasText:'背景已设置'}).waitFor();
await page.locator('#overlay').fill('20');await page.locator('#overlay').dispatchEvent('change');
await page.evaluate(()=>window.close());await new Promise(r=>app.process().once('exit',r));
const saved=JSON.parse(fs.readFileSync(file,'utf8'));
assert.ok(saved.projects[0].logo.startsWith('data:image/png;base64,'));assert.equal(saved.settings.overlay,20);
app=await electron.launch(options);page=await app.firstWindow();
await page.waitForFunction(()=>document.querySelector('.project-logo')?.naturalWidth>0);
assert.equal(await page.evaluate(()=>document.body.style.getPropertyValue('--veil')),'0.2');
await app.close();
console.log('Desktop appearance passed: old background migration, image import, disk persistence and restart.');
